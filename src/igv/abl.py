def download_hauser2018(cache_dir: Path) -> Path:
    """Download the Hauser 2018 Supplementary Data 3 XLSX and convert to CSV.

    The XLSX is fetched from the authors' GitHub repository and converted to
    CSV using pandas + openpyxl (required only at fetch time). The CSV is
    cached at ``cache_dir / HAUSER2018_CACHE_NAME``; subsequent calls return
    the cache immediately.

    The cache key includes the dataset name so it cannot collide with other
    downloads in the same directory.
    """
    cache_dir = Path(cache_dir)
    dest = cache_dir / HAUSER2018_CACHE_NAME

    if dest.exists():
        return dest

    xlsx_path = cache_dir / "hauser2018_abl_supp3.xlsx"
    _atomic_download(HAUSER2018_XLSX_URL, xlsx_path)

    df = pd.read_excel(xlsx_path, engine="openpyxl")
    cache_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(dest, index=False)
    xlsx_path.unlink(missing_ok=True)

    return dest


def load_hauser2018(cache_dir: Path) -> pd.DataFrame:
    """Download (if needed) and read the Hauser 2018 dataset.

    Returns a DataFrame with the raw columns from Supplementary Data 3 plus
    two computed columns:

    - ``structure_type``: ``"xtal"`` for the 6 ABL TKIs with co-crystal
      structures, ``"docked"`` for erlotinib/gefitinib.
    - ``dlog10_ic50``: ``DDG_exp / RT_LN10_300K``, the raw delta-log10(IC50)
      before the RT conversion. NaN where DDG_exp is NaN.
    """
    path = download_hauser2018(cache_dir)
    return _add_derived_columns(pd.read_csv(path))


def load_hauser2018_from_csv(path: Path) -> pd.DataFrame:
    """Load a pre-fetched Hauser 2018 CSV (for offline use / testing)."""
    return _add_derived_columns(pd.read_csv(path))


def _add_derived_columns(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    df["structure_type"] = df["TKI"].apply(lambda t: "docked" if t in EGFR_TKIS else "xtal")
    df["dlog10_ic50"] = df["DDG_exp"] / RT_LN10_300K
    df["ic50_suspect"] = _flag_ic50_suspect(df)
    return df


def _flag_ic50_suspect(df: pd.DataFrame) -> pd.Series:
    """Flag rows where raw IC50 is inconsistent with DDG_exp.

    For each row with both IC50 and DDG_exp present, compute the implied
    log10(WT IC50) from each independently:

      from IC50:    log10(IC50_mut)
      from DDG_exp: log10(IC50_mut) = DDG_exp / RT_LN10_300K + log10(IC50_wt)

    The per-TKI reference log10(WT IC50) is the median of the implied values
    (robust to the outlier). A row is flagged if its implied value deviates
    from this reference beyond ``IC50_CONSISTENCY_TOL_LOG10``.

    Returns a boolean Series aligned with *df*. Rows with NaN IC50 or
    DDG_exp get False (not suspect -- they have no IC50 to be wrong).
    """
    flags = pd.Series(False, index=df.index)
    has_both = df["IC50"].notna() & df["DDG_exp"].notna() & (df["IC50"] > 0)

    if not has_both.any():
        return flags

    implied_log10_wt = (
        np.log10(df.loc[has_both, "IC50"]) - df.loc[has_both, "DDG_exp"] / RT_LN10_300K
    )

    tki_ref: dict[str, float] = {}
    for tki in df.loc[has_both, "TKI"].unique():
        tki_mask = df.loc[has_both, "TKI"] == tki
        tki_ref[tki] = float(np.median(implied_log10_wt[tki_mask]))

    for idx in implied_log10_wt.index:
        tki = df.loc[idx, "TKI"]
        ref = tki_ref.get(tki)
        if ref is not None:
            deviation = abs(implied_log10_wt[idx] - ref)
            if deviation > IC50_CONSISTENCY_TOL_LOG10:
                flags[idx] = True

    return flags


def validate_ic50_consistency(df: pd.DataFrame) -> pd.DataFrame:
    """Return rows where ``IC50`` is inconsistent with ``DDG_exp``.

    This is the caller-facing validation entry point. It returns a DataFrame
    of suspect rows (a subset of the input) with an additional
    ``ic50_deviation_log10`` column showing the magnitude of the discrepancy.
    An empty return means all rows are consistent.

    Raises ``ValueError`` if the ``ic50_suspect`` column is missing (i.e. the
    DataFrame was not loaded through this module's loaders).
    """
    if "ic50_suspect" not in df.columns:
        raise ValueError(
            "DataFrame lacks 'ic50_suspect' column. "
            "Load via load_hauser2018() or load_hauser2018_from_csv()."
        )
    suspect = df[df["ic50_suspect"]].copy()
    if len(suspect) == 0:
        suspect["ic50_deviation_log10"] = pd.Series(dtype=float)
        return suspect

    has_both = suspect["IC50"].notna() & suspect["DDG_exp"].notna() & (suspect["IC50"] > 0)
    implied = (
        np.log10(suspect.loc[has_both, "IC50"]) - suspect.loc[has_both, "DDG_exp"] / RT_LN10_300K
    )

    all_measured = df[df["IC50"].notna() & df["DDG_exp"].notna() & (df["IC50"] > 0)]
    tki_ref: dict[str, float] = {}
    for tki in all_measured["TKI"].unique():
        tki_mask = all_measured["TKI"] == tki
        vals = (
            np.log10(all_measured.loc[tki_mask, "IC50"])
            - all_measured.loc[tki_mask, "DDG_exp"] / RT_LN10_300K
        )
        tki_ref[tki] = float(np.median(vals))

    deviations = pd.Series(np.nan, index=suspect.index)
    for idx in implied.index:
        tki = suspect.loc[idx, "TKI"]
        ref = tki_ref.get(tki)
        if ref is not None:
            deviations[idx] = abs(implied[idx] - ref)

    suspect["ic50_deviation_log10"] = deviations
    return suspect


