@dataclass(frozen=True)
class MappedMeasurement:
    """A Hauser measurement mapped onto a PDB chain."""

    mutation: AblMutation
    tki: str
    ic50_nm: float
    ddg_exp: float
    dlog10_ic50: float
    pdb_index: int
    pdb_id: str


@dataclass(frozen=True)
class UnmappedMeasurement:
    """A measurement whose residue is absent or unresolved in the structure."""

    mutation: AblMutation
    tki: str
    reason: str


def map_to_pdb(
    df: pd.DataFrame,
    residue_ids: list[str],
    sequence: str,
    *,
    chain: str,
    pdb_id: str,
) -> tuple[list[MappedMeasurement], list[UnmappedMeasurement]]:
    """Map each measured row onto 0-based indices in a PDB chain.

    Verifies wild-type amino acid agreement between the dataset and the PDB
    sequence. Mutations at positions absent from the structure, or with
    wild-type mismatches, are returned as ``UnmappedMeasurement`` entries
    rather than silently dropped.

    Parameters
    ----------
    df : DataFrame
        Hauser 2018 data (must have columns ``mutation``, ``TKI``, ``IC50``,
        ``DDG_exp``).
    residue_ids : list[str]
        Author residue IDs for the chain (from ``read_pdb_residue_ids``).
    sequence : str
        One-letter sequence for the chain.
    chain : str
        PDB chain letter.
    pdb_id : str
        PDB identifier (for provenance in the output).

    Returns
    -------
    mapped : list[MappedMeasurement]
    unmapped : list[UnmappedMeasurement]
    """
    id_to_idx = {rid: i for i, rid in enumerate(residue_ids)}

    mapped: list[MappedMeasurement] = []
    unmapped: list[UnmappedMeasurement] = []

    for _, row in df.iterrows():
        mut = parse_mutation(row["mutation"])
        resnum_str = str(mut.resnum)
        tki = row["TKI"]

        if pd.isna(row.get("IC50")) or pd.isna(row.get("DDG_exp")):
            continue

        if resnum_str not in id_to_idx:
            unmapped.append(
                UnmappedMeasurement(
                    mutation=mut,
                    tki=tki,
                    reason=f"residue {mut.resnum} absent from {pdb_id} chain {chain}",
                )
            )
            continue

        idx = id_to_idx[resnum_str]
        pdb_aa = sequence[idx]
        if pdb_aa != mut.wt_aa:
            unmapped.append(
                UnmappedMeasurement(
                    mutation=mut,
                    tki=tki,
                    reason=(
                        f"wild-type mismatch at {mut.resnum}: "
                        f"dataset says {mut.wt_aa}, PDB has {pdb_aa}"
                    ),
                )
            )
            continue

        ddg = float(row["DDG_exp"])
        mapped.append(
            MappedMeasurement(
                mutation=mut,
                tki=tki,
                ic50_nm=float(row["IC50"]),
                ddg_exp=ddg,
                dlog10_ic50=ddg / RT_LN10_300K,
                pdb_index=idx,
                pdb_id=pdb_id,
            )
        )

    return mapped, unmapped


def map_resnum_to_pdb_index(
    resnum: int,
    residue_ids: list[str],
    sequence: str,
    *,
    expected_wt: str | None = None,
) -> int | None:
    """Map a single ABL1 1b residue number to a 0-based PDB chain index.

    Returns ``None`` if the residue is absent. Raises ``ValueError`` on a
    wild-type mismatch when *expected_wt* is provided.
    """
    resnum_str = str(resnum)
    id_to_idx = {rid: i for i, rid in enumerate(residue_ids)}
    if resnum_str not in id_to_idx:
        return None
    idx = id_to_idx[resnum_str]
    if expected_wt is not None and sequence[idx] != expected_wt:
        raise ValueError(
            f"Wild-type mismatch at {resnum}: expected {expected_wt}, "
            f"found {sequence[idx]} at index {idx}"
        )
    return idx


