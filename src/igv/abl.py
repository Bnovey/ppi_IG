@dataclass(frozen=True)
class AblMutation:
    """A single-point mutation in ABL1 kinase domain (isoform 1b numbering)."""

    wt_aa: str
    resnum: int
    mut_aa: str

    def __str__(self) -> str:
        return f"{self.wt_aa}{self.resnum}{self.mut_aa}"


def parse_mutation(s: str) -> AblMutation:
    """Parse a mutation string like ``T315I`` into an AblMutation."""
    m = _MUTATION_RE.match(s.strip())
    if m is None:
        raise ValueError(f"Malformed ABL mutation code: {s!r}")
    return AblMutation(wt_aa=m.group(1), resnum=int(m.group(2)), mut_aa=m.group(3))


