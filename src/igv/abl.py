"""Hauser et al. 2018 ABL1 tyrosine-kinase-inhibitor resistance dataset loader.

Source: Hauser et al. "Predicting resistance of clinical Abl mutations to
targeted kinase inhibitors using alchemical free-energy calculations",
Commun Biol 1:70 (2018). https://pmc.ncbi.nlm.nih.gov/articles/PMC6110136/

Data: Supplementary Data 3 from the authors' GitHub repository at
https://github.com/kehauser/Predicting-resistance-of-clinical-Abl-mutations-to-targeted-kinase-inhibitors-using-FEP

Inhibitors
----------
The dataset contains **8 inhibitors**: 6 ABL-targeting TKIs with co-crystal
structures (axitinib, bosutinib, dasatinib, imatinib, nilotinib, ponatinib)
and 2 EGFR-targeting TKIs (erlotinib, gefitinib) included as off-target
controls. The EGFR TKIs lack ABL co-crystal structures; their poses were
generated by **docking** (Glide-SP into the bosutinib-bound ABL structure),
not from experimental crystallography. The loader flags these as
``structure_type="docked"`` to distinguish them from the co-crystal-backed
measurements (``structure_type="xtal"``).

Numbering convention
--------------------
Mutations use **ABL1 isoform 1b** numbering -- the standard in clinical
oncology. T315 is the gatekeeper residue. ABL1 isoform 1a adds 18 residues
at the N-terminus, so the same residue is T333 in 1a (UniProt P00519
canonical numbering). All six ABL co-crystal PDB structures use 1b numbering
directly; the authors confirmed they adjusted 1OPJ and 4XEY to match
P00519-1.

Verification of 1b numbering: all 31 measured mutations were mapped against
PDB 4WA9 chain B (the axitinib co-crystal, human ABL1). 31/31 wild-type
amino acids match with zero mismatches, confirming the mutation residue
numbers are 1b. Under 1a numbering (+18), position 244 would map to 262,
which is glycine in 4WA9, not methionine -- the mismatch is immediate.

Sign convention
---------------
``DDG_exp`` is **DDG in kcal/mol**: positive means the mutation *increases*
IC50 (resistance, weaker inhibitor binding); negative means the mutation
*decreases* IC50 (sensitisation, tighter binding).

The paper defines (Methods, Eq. 2):

    DDG = -RT * ln(IC50_WT / IC50_mut) = RT * ln(IC50_mut / IC50_WT)

with **T = 300 K** and RT = 0.596 kcal/mol. The temperature is stated in
the paper text (Methods): "T is taken to be room temperature (300 K)". One
log10 unit of IC50 change therefore equals **1.373 kcal/mol**
(= 2.303 * 0.596), NOT the 298 K value of 1.364. Practically the difference
is 0.7% and invisible to rank correlation; it matters only for a calibration
slope.

Primary and derived columns
---------------------------
- ``IC50`` (nM): raw IC50 as reported by Schrock et al. 2013.
  **One cell is corrupt**: ponatinib / G250E reports IC50 = 0.021 nM, ~140x
  below every other ponatinib IC50 (range 3-16 nM). The ``DDG_exp`` for that
  row (0.30 kcal/mol) is self-consistent with a WT of 3 nM and an implied
  mutant IC50 of ~4.9 nM. The ``IC50`` cell cannot be reconciled and is not
  a clean unit conversion error. It is flagged in the ``ic50_suspect`` column
  but not repaired: fabricating a measurement is worse than marking one.
- ``DDG_exp`` (kcal/mol): the paper's DDG, computed at T=300K. **This is the
  trustworthy column** -- self-consistent across all rows including G250E.
  Use this (or ``dlog10_ic50``) as the ground truth, not raw ``IC50``.
- ``dlog10_ic50``: **dlog10(IC50) = log10(IC50_mut) - log10(IC50_wt)**, the
  raw pIC50 shift. Computed by this loader from DDG_exp via
  ``dlog10 = DDG_exp / RT_LN10_300K``. Exposed so downstream code can work
  in log10 units without inheriting an RT conversion.
- ``ic50_suspect``: boolean, True for rows where the raw ``IC50`` deviates
  from ``DDG_exp`` beyond the stated tolerance (see
  ``IC50_CONSISTENCY_TOL_LOG10``). Currently flags exactly one row:
  ponatinib / G250E.

Assay type
----------
All 131 ABL TKI measurements and 13 EGFR measurements come from
**cell-viability IC50 assays** (Ba/F3 cells expressing BCR-ABL), not
biochemical binding assays. The paper's own comparison of IC50-derived ΔΔG
against Kd-derived ΔΔG (Supplementary Data 1, Fig. 2d, Davis et al.) gives
**RMSE = 0.813 kcal/mol at n=27** -- this is the measured noise floor of the
IC50-to-binding-affinity conversion.
"""

