def summary(df: pd.DataFrame) -> dict:
    """Compute summary statistics for the Hauser 2018 dataset.

    Expects the raw DataFrame (before filtering).
    """
    meas = measured(df)
    abl = abl_only(meas)

    per_tki: dict[str, int] = {}
    for tki in sorted(df["TKI"].unique()):
        sub = meas[meas["TKI"] == tki]
        per_tki[tki] = len(sub)

    mutations = set()
    positions = set()
    for m_str in meas["mutation"].unique():
        mut = parse_mutation(m_str)
        mutations.add(str(mut))
        positions.add(mut.resnum)

    ddg_vals = meas["DDG_exp"].values

    return {
        "total_rows": len(df),
        "total_measured": len(meas),
        "abl_measured": len(abl),
        "egfr_measured": len(meas) - len(abl),
        "per_tki": per_tki,
        "n_distinct_mutations": len(mutations),
        "n_distinct_positions": len(positions),
        "ddg_mean": float(np.nanmean(ddg_vals)),
        "ddg_std": float(np.nanstd(ddg_vals)),
        "ddg_min": float(np.nanmin(ddg_vals)),
        "ddg_max": float(np.nanmax(ddg_vals)),
        "ddg_median": float(np.nanmedian(ddg_vals)),
        "n_resistance": int((ddg_vals > 0).sum()),
        "n_sensitising": int((ddg_vals < 0).sum()),
        "n_neutral": int((ddg_vals == 0).sum()),
    }
