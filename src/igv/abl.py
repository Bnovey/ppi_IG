def measured(df: pd.DataFrame) -> pd.DataFrame:
    """Rows with both IC50 and DDG_exp present (drop NaN measurements)."""
    mask = df["IC50"].notna() & df["DDG_exp"].notna()
    return df[mask].reset_index(drop=True)


def abl_only(df: pd.DataFrame) -> pd.DataFrame:
    """Rows for the 6 ABL-targeting TKIs (drop EGFR controls erlotinib/gefitinib).

    These are the measurements backed by experimental co-crystal structures.
    """
    mask = df["TKI"].isin(ABL_TKIS)
    return df[mask].reset_index(drop=True)


def xtal_only(df: pd.DataFrame) -> pd.DataFrame:
    """Rows whose inhibitor has an experimental co-crystal structure.

    Equivalent to ``abl_only`` but keyed on ``structure_type`` so it works
    regardless of which column was used to derive the flag.
    """
    if "structure_type" not in df.columns:
        return abl_only(df)
    return df[df["structure_type"] == "xtal"].reset_index(drop=True)


def docked_only(df: pd.DataFrame) -> pd.DataFrame:
    """Rows whose inhibitor pose was generated by docking (erlotinib/gefitinib)."""
    if "structure_type" not in df.columns:
        mask = df["TKI"].isin(EGFR_TKIS)
        return df[mask].reset_index(drop=True)
    return df[df["structure_type"] == "docked"].reset_index(drop=True)


